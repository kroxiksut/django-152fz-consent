@transaction.atomic
def bootstrap_sample_documents(*, using: str = DEFAULT_DB_ALIAS) -> dict[str, Any]:
    """Загрузить коробочные sample-документы в БД идемпотентно.

    Загрузка intentionally не использует `publish_document_revision()`: sample-тексты
    не должны становиться live-ревизиями и не должны влиять на существующие consent
    records или переводить их в `outdated`.
    """
    documents_manager = LegalDocument.objects.using(using)
    revisions_manager = DocumentRevision.objects.using(using)
    summary: dict[str, Any] = {
        "created_purposes": 0,
        "existing_purposes": 0,
        "created_documents": 0,
        "created_revisions": 0,
        "existing_samples": 0,
        "skipped_existing_streams": 0,
        "created_access_policies": 0,
        "existing_access_policies": 0,
        "created_audience_rules": 0,
        "existing_audience_rules": 0,
        "items": [],
    }

    purpose_by_code = _ensure_sample_purposes(
        using=using,
        summary=summary,
    )
    for sample in get_sample_document_definitions():
        document, document_created = documents_manager.get_or_create(
            code=sample.document_code,
            defaults={
                "title": sample.title,
                "document_type": sample.document_type,
                "description": sample.description,
                "is_active": False,
            },
        )
        if document_created:
            summary["created_documents"] += 1

        existing_revisions = list(
            revisions_manager.filter(
                document_id=document.pk,
                purpose_code=sample.purpose_code,
            ).order_by("version")
        )
        existing_sample = next(
            (
                revision
                for revision in existing_revisions
                if isinstance(revision.meta, dict)
                and revision.meta.get("sample_key") == sample.key
            ),
            None,
        )
        if existing_sample is not None:
            summary["existing_samples"] += 1
            summary["items"].append(
                {
                    "key": sample.key,
                    "document_code": sample.document_code,
                    "status": "exists",
                    "revision_id": existing_sample.pk,
                }
            )
            continue

        if existing_revisions:
            summary["skipped_existing_streams"] += 1
            summary["items"].append(
                {
                    "key": sample.key,
                    "document_code": sample.document_code,
                    "status": "skipped_existing_stream",
                }
            )
            continue

        revision = revisions_manager.create(
            document=document,
            purpose_code=sample.purpose_code,
            version=1,
            format=DocumentRevision.ContentFormat.MARKDOWN,
            content_text=sample.content_text,
            fields_snapshot=list(sample.fields_snapshot),
            meta=_build_sample_revision_meta(sample),
            is_active=False,
            is_box_template=True,
            published_at=timezone.now(),
        )
        summary["created_revisions"] += 1
        summary["items"].append(
            {
                "key": sample.key,
                "document_code": sample.document_code,
                "status": "created",
                "revision_id": revision.pk,
            }
        )

    _bootstrap_sample_access_policies(
        using=using,
        purpose_by_code=purpose_by_code,
        summary=summary,
    )
    _bootstrap_sample_audience_rules(
        using=using,
        purpose_by_code=purpose_by_code,
        summary=summary,
    )

    log_module_operation(
        operation_code="service.core.bootstrap_sample_documents",
        source="box_templates.documents",
        target_model="django_consent_152fz.DocumentRevision",
        summary="Bootstrap sample consent templates, policies and audience rules.",
        payload={"database": using},
        result=summary,
    )
    return summary


def _ensure_sample_purposes(
    *,
    using: str,
    summary: dict[str, Any],
) -> dict[str, ConsentPurpose]:
    """Create missing purpose codes for boxed samples."""
    purposes_manager = ConsentPurpose.objects.using(using)

    required_codes = {sample.purpose_code for sample in _SAMPLE_DOCUMENT_DEFINITIONS}
    required_codes.update(
        sample.purpose_code for sample in _SAMPLE_ACCESS_POLICY_DEFINITIONS
    )
    required_codes.update(
        sample.purpose_code for sample in _SAMPLE_AUDIENCE_RULE_DEFINITIONS
    )

    purpose_by_code: dict[str, ConsentPurpose] = {}
    for purpose_code in sorted(required_codes):
        defaults = _SAMPLE_PURPOSE_DEFAULTS.get(
            purpose_code,
            {
                "title": f"Шаблонная цель: {purpose_code}",
                "description": (
                    "Техническая шаблонная цель, созданная bootstrap-процессом "
                    "для коробочных документов."
                ),
                "fields_config": [],
            },
        )
        purpose, created = purposes_manager.get_or_create(
            code=purpose_code,
            defaults={
                "title": str(defaults["title"]),
                "description": str(defaults["description"]),
                "fields_config": list(defaults["fields_config"]),
                "withdraw_strategy": constants.WITHDRAW_STRATEGY_BLOCK,
                "reconsent_mode": constants.RECONSENT_MODE_SOFT,
                "is_experimental": True,
                "is_active": False,
            },
        )
        if created:
            summary["created_purposes"] += 1
        else:
            summary["existing_purposes"] += 1
        purpose_by_code[purpose_code] = purpose
    return purpose_by_code


def _bootstrap_sample_access_policies(
    *,
    using: str,
    purpose_by_code: dict[str, ConsentPurpose],
    summary: dict[str, Any],
) -> None:
    """Create boxed access policy records."""
    policies_manager = ConsentAccessPolicy.objects.using(using)
    documents_manager = LegalDocument.objects.using(using)

    for sample in get_sample_access_policy_definitions():
        purpose = purpose_by_code.get(sample.purpose_code)
        document = documents_manager.filter(code=sample.document_code).first()
        if purpose is None or document is None:
            continue
        _policy, created = policies_manager.get_or_create(
            code=sample.code,
            defaults={
                "title": sample.title,
                "description": sample.description,
                "purpose": purpose,
                "document": document,
                "resource_code": sample.resource_code,
                "app_label": "",
                "model_name": "",
                "action": sample.action,
                "on_missing_consent": sample.on_missing_consent,
                "on_outdated_consent": sample.on_outdated_consent,
                "is_active": False,
                "notes": (f"{sample.notes}\n[bundled_sample_policy_key={sample.key}]"),
                "extra_meta": {
                    "starter_template": True,
                    "sample_key": sample.key,
                    "catalog_version": _SAMPLE_META_BASE["catalog_version"],
                },
            },
        )
        if created:
            summary["created_access_policies"] += 1
        else:
            summary["existing_access_policies"] += 1


def _bootstrap_sample_audience_rules(
    *,
    using: str,
    purpose_by_code: dict[str, ConsentPurpose],
    summary: dict[str, Any],
) -> None:
    """Create boxed audience rules with safe idempotency."""
    rules_manager = ConsentAudienceRule.objects.using(using)
    documents_manager = LegalDocument.objects.using(using)

    for sample in get_sample_audience_rule_definitions():
        purpose = purpose_by_code.get(sample.purpose_code)
        document = documents_manager.filter(code=sample.document_code).first()
        if purpose is None or document is None:
            continue
        marker = f"[bundled_sample_rule_key={sample.key}]"
        existing = rules_manager.filter(
            purpose=purpose,
            document=document,
            scope_mode=sample.scope_mode,
            notes__contains=marker,
        ).first()
        if existing is not None:
            summary["existing_audience_rules"] += 1
            continue

        rules_manager.create(
            purpose=purpose,
            document=document,
            scope_mode=sample.scope_mode,
            group=None,
            is_required=sample.is_required,
            is_active=False,
            notes=f"{sample.notes}\n{marker}",
            created_by=None,
        )
        summary["created_audience_rules"] += 1


def bootstrap_sample_documents_post_migrate(
    sender,
    app_config=None,
    verbosity: int = 1,
    using: str = DEFAULT_DB_ALIAS,
    **kwargs,
) -> dict[str, Any] | None:
    """Post-migrate hook for secure autoloading of sample documents."""
    if not is_sample_documents_auto_bootstrap_enabled():
        return None
    return bootstrap_sample_documents(using=using)


def is_sample_documents_bootstrap_allowed(*, force: bool = False) -> bool:
    """Check if bootstrap can be launched in the current settings mode."""
    if force:
        return True
    return (
        get_sample_documents_load_mode()
        != constants.SAMPLE_DOCUMENTS_LOAD_MODE_DISABLED
    )


def _build_sample_revision_meta(sample: SampleDocumentDefinition) -> dict[str, Any]:
    """Collect normalized meta for starter template revision."""
    meta = dict(_SAMPLE_META_BASE)
    meta.update(
        {
            "sample_key": sample.key,
            "sample_purpose_code": sample.purpose_code,
            "sample_document_code": sample.document_code,
            "warning": _SAMPLE_NOTICE,
        }
    )
    return meta
